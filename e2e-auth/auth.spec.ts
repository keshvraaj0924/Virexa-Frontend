import { test, expect } from '@playwright/test'

test('real FastAPI registration, SSR, isolation, repeated and interrupted flows, login and revocation', async ({ page, browser }) => {
  const password = 'Isolated-test-password-927!'
  const email = `owner-${Date.now()}@example.com`
  const origin = 'http://127.0.0.1:3000'
  // Every auth response comes from FastAPI. One test delays forwarding, never mocks a response.
  await page.goto('/app')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('link', { name: 'Create a workspace' }).click()
  await page.getByLabel('Full name').fill('Interrupted entry')
  await page.getByRole('link', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goBack()
  await expect(page).toHaveURL(/\/register$/)
  await page.getByLabel('Full name').fill('Alpha Owner')
  await page.getByLabel('Organization', { exact: true }).fill('Alpha Workspace')
  await page.getByLabel('Work email').fill(email)
  await page.getByLabel(/^Password/).fill(password)
  let submissions = 0
  page.on('request', request => { if (request.url().endsWith('/auth/register') && request.method() === 'POST') submissions++ })
  await page.locator('form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
  await expect(page).toHaveURL(`${origin}/app`)
  expect(submissions).toBe(1)
  await expect(page.getByRole('heading', { name: 'Authentication preview' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Documents', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(page.getByText(email)).toBeVisible()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: 'test-results/workspace-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/workspace-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  const cookies = await page.context().cookies()
  const sessionCookie = cookies.find(cookie => cookie.httpOnly)
  expect(sessionCookie).toBeTruthy()
  expect(sessionCookie!.sameSite).toBe('Lax')
  expect(sessionCookie!.path).toBe('/')
  expect(await page.evaluate(() => document.cookie)).not.toContain(sessionCookie!.name)
  const sessionResponse = await page.request.get('/api/v1/auth/session')
  expect(sessionResponse.status()).toBe(200)
  expect(sessionResponse.headers()['cache-control']).toContain('no-store')
  const session = (await sessionResponse.json()).data
  expect(session.user.email).toBe(email)
  expect(JSON.stringify(session)).not.toContain(sessionCookie!.value)
  expect((await page.request.get('/api/v1/me')).status()).toBe(200)
  expect((await page.request.get(`/api/v1/organizations/${session.user.organizationId}`)).status()).toBe(200)
  expect((await page.request.get('/api/v1/workflows')).status()).toBe(404)
  await page.goto('/app/documents')
  await expect(page).toHaveURL(`${origin}/app`)

  const other = await browser.newContext({ baseURL: origin })
  const second = await other.request.post('/api/v1/auth/register', { headers: { Origin: origin }, data: { displayName: 'Beta Owner', email: `beta-${email}`, password, organizationName: 'Beta Workspace' } })
  expect(second.status()).toBe(201)
  const secondSession = (await second.json()).data
  expect(secondSession.user.organizationId).not.toBe(session.user.organizationId)
  expect((await other.request.get(`/api/v1/organizations/${session.user.organizationId}`)).status()).toBe(404)
  expect((await page.request.get(`/api/v1/organizations/${secondSession.user.organizationId}`)).status()).toBe(404)
  expect((await page.request.post('/api/v1/auth/logout', { headers: { Origin: 'https://evil.example', 'X-Forwarded-Host': '127.0.0.1:3000' } })).status()).toBe(403)
  expect((await page.request.post('/api/v1/auth/logout')).status()).toBe(403)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(200)
  await other.close()

  const stale = await browser.newContext({ baseURL: origin })
  await stale.addCookies(cookies)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  expect((await stale.request.get('/api/v1/auth/session')).status()).toBe(401)
  await stale.close()
  await page.goBack()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByText(email)).toHaveCount(0)
  await page.goto('/app')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByLabel('Work email').fill(email)
  await page.getByLabel(/^Password/).fill('Wrong-password-927!')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: /credential|password|email/i })).toBeVisible()
  await page.getByLabel(/^Password/).fill(password)
  // Hold a real request before forwarding, navigate away, then let FastAPI finish it.
  let release!: () => void
  let intercepted!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  const started = new Promise<void>(resolve => { intercepted = resolve })
  await page.route('**/api/v1/auth/login', async route => { intercepted(); await held; await route.continue() }, { times: 1 })
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await started
  await page.getByRole('link', { name: 'Create a workspace' }).click()
  await expect(page).toHaveURL(/\/register$/)
  const completedLogin = page.waitForResponse(response => response.url().endsWith('/auth/login'))
  release()
  const loginResponse = await completedLogin
  expect(loginResponse.status()).toBe(200)
  await loginResponse.finished()
  await page.waitForTimeout(250)
  await expect(page.getByRole('heading', { name: 'Create your workspace.' })).toBeVisible()
  await expect(page).toHaveURL(/\/register$/)
  await page.goto('/app')
  await expect(page).toHaveURL(`${origin}/app`)
  await page.reload()
  await expect(page.getByText(email)).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
})
