test('reload/back discard codes and delivery failure does not enter verification', async ({ page }) => {
  await page.goto('/register')
  await page.getByLabel('Full name').fill('Interrupted Owner')
  await page.getByLabel('Email', { exact: true }).fill(`interrupted-${Date.now()}@example.com`)
  await page.getByRole('button', { name: 'Send verification code' }).click()
  await page.getByLabel('Verification code').fill('synthetic-not-persisted')
  await page.reload()
  await expect(page.getByLabel('Full name')).toBeVisible()
  await expect(page.getByLabel('Verification code')).toHaveCount(0)
  await page.getByRole('link', { name: 'Sign in', exact: true }).click()
  await page.goBack()
  await expect(page.getByLabel('Verification code')).toHaveCount(0)
  await page.getByLabel('Full name').fill('Delivery Failure')
  // The loopback-only sink rejects non-fixture domains. No external email is sent.
  await page.getByLabel('Email', { exact: true }).fill(`delivery-${Date.now()}@unavailable.invalid`)
  await page.getByRole('button', { name: 'Send verification code' }).click()
  await expect(page.locator('form').getByRole('alert')).toContainText(/unavailable|delivery|send/i)
  await expect(page.getByLabel('Verification code')).toHaveCount(0)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  expect((await page.request.post('/api/v1/auth/register', { headers, data: { displayName: 'Bypass Attempt', organizationName: 'Bypass', email: 'bypass@example.com', password } })).status()).toBe(410)
})

test('resend rotates the real code after cooldown and expiry offers a safe restart', async ({ page }) => {
  const email = `resend-${Date.now()}@example.com`
  await page.goto('/register')
  await page.getByLabel('Full name').fill('Resend Owner')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Send verification code' }).click()
  await expect(page.getByLabel('Verification code')).toBeVisible()
  const oldCode = capturedCode(email)
  const resend = page.getByRole('button', { name: 'Resend code', exact: true })
  // Wait through the actual server cooldown, never bypass verification or mock delivery.
  await expect(resend).toBeEnabled({ timeout: 65000 })
  await resend.click()
  await expect(page.getByRole('button', { name: /Resend in/ })).toBeDisabled()
  await page.getByLabel('Verification code').fill(oldCode)
  await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  await expect(page.locator('form').getByRole('alert')).toBeVisible()
  await expect(page.getByLabel('Verification code')).toBeVisible()
  await page.getByLabel('Verification code').fill(capturedCode(email))
  await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  await expect(page.getByLabel(/^Password/)).toBeVisible()
  await page.clock.install()
  await page.clock.fastForward(601000)
  await expect(page.getByRole('status')).toContainText('expired')
  await expect(page.getByRole('button', { name: 'Create workspace', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Edit details' }).click()
  await expect(page.getByLabel('Full name')).toBeVisible()
  await expect(page.getByLabel(/^Password/)).toHaveCount(0)
})

test('lost completion response reconciles the session or offers a non-replaying sign-in recovery', async ({ page }) => {
  const email = `lost-response-${Date.now()}@example.com`
  await page.goto('/register')
  await page.getByLabel('Full name').fill('Response Recovery')
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByRole('button', { name: 'Send verification code' }).click()
  await expect(page.getByLabel('Verification code')).toBeVisible()
  await page.getByLabel('Verification code').fill(capturedCode(email))
  await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  await page.getByLabel(/^Password/).fill(password)
  let completions = 0
  await page.route('**/api/v1/auth/signup/complete', async route => {
    completions++
    expect((await route.fetch()).status()).toBe(201)
    await route.abort('failed')
  }, { times: 1 })
  await page.getByRole('button', { name: 'Create workspace', exact: true }).click()
  await expect.poll(async () => page.url().endsWith('/app') || await page.getByRole('button', { name: 'Restart verification' }).isVisible()).toBe(true)
  expect(completions).toBe(1)
  if (!page.url().endsWith('/app')) {
    await expect(page.getByLabel(/^Password/)).toHaveCount(0)
    await page.locator('.vx-signup-recovery').getByRole('link', { name: 'Sign in', exact: true }).click()
    await page.getByLabel('Email', { exact: true }).fill(email)
    await page.getByLabel(/^Password/).fill(password)
    await page.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(page).toHaveURL(`${origin}/app`)
  }
  await expect(page.locator('.vx-workspace-tenant')).toContainText('Individual workspace')
})
