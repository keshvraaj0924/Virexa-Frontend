import { test, expect } from '@playwright/test'
import { capturedCode, verifiedAccount } from '../e2e-support/verification'
const origin = 'http://127.0.0.1:3000'
const password = 'Synthetic-unique-passphrase-927!'
const headers = { Origin: origin }

test('individual verified signup, isolated workspace, truthful usage and account-kind login', async ({ page, browser }) => {
  const email = `individual-${Date.now()}@example.com`
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/register')
  await expect(page.getByRole('radio', { name: /Individual/ })).toBeChecked()
  await expect(page.getByLabel('Organization name')).toHaveCount(0)
  await expect(page.getByLabel(/^Password/)).toHaveCount(0)
  await page.getByLabel('Full name').fill('Individual Owner')
  await page.getByLabel('Email', { exact: true }).fill(email)
  let starts = 0, verifies = 0, completions = 0
  page.on('request', request => {
    if (request.method() !== 'POST') return
    if (request.url().endsWith('/auth/signup/start')) starts++
    if (request.url().endsWith('/auth/signup/verify')) verifies++
    if (request.url().endsWith('/auth/signup/complete')) completions++
  })
  await page.locator('form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
  await expect(page.getByLabel('Verification code')).toBeVisible()
  expect(starts).toBe(1)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  await expect(page.getByRole('button', { name: /Resend in/ })).toBeDisabled()
  await page.getByLabel('Verification code').fill('wrong-synthetic-code')
  await page.getByRole('button', { name: 'Verify email', exact: true }).click()
  await expect(page.locator('form').getByRole('alert')).toBeVisible()
  await expect(page.getByLabel(/^Password/)).toHaveCount(0)
  await expect(page.getByLabel('Verification code')).toBeVisible()
  await page.getByLabel('Verification code').fill(capturedCode(email))
  await page.locator('form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
  await expect(page.getByLabel(/^Password/)).toBeVisible()
  expect(verifies).toBe(2)
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  await expect(page.getByLabel('Verification code')).toHaveCount(0)
  await page.getByLabel(/^Password/).fill(password)
  await page.locator('form').evaluate((form: HTMLFormElement) => { form.requestSubmit(); form.requestSubmit() })
  await expect(page).toHaveURL(`${origin}/app`)
  expect(completions).toBe(1)
  await expect(page.locator('.vx-workspace-tenant')).toContainText('Individual workspace')
  const individual = (await (await page.request.get('/api/v1/auth/session')).json()).data.user
  expect(individual.accountType).toBe('individual')
  const stored = await page.evaluate(() => ({ local: { ...localStorage }, session: { ...sessionStorage } }))
  expect(JSON.stringify(stored)).not.toMatch(/setupToken|challengeId|verification|password/i)
  await page.goto('/app/usage')
  await expect(page.getByText(/allowance belongs to your private workspace/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Organization usage' })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/individual-usage-mobile.png', fullPage: true })
  const organization = await browser.newContext({ baseURL: origin })
  const team = await verifiedAccount(organization.request, { accountType: 'organization', displayName: 'Team Owner', organizationName: 'Synthetic Startup', email: `team-${email}`, password })
  expect(team.user.accountType).toBe('organization')
  expect(team.user.organizationId).not.toBe(individual.organizationId)
  expect((await page.request.get(`/api/v1/organizations/${team.user.organizationId}`)).status()).toBe(404)
  expect((await organization.request.get(`/api/v1/organizations/${individual.organizationId}`)).status()).toBe(404)
  await organization.close()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await page.getByRole('radio', { name: /Organization/ }).check()
  await page.getByLabel('Email', { exact: true }).fill(email)
  await page.getByLabel(/^Password/).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('form').getByRole('alert')).toBeVisible()
  expect((await page.request.get('/api/v1/auth/session')).status()).toBe(401)
  await page.getByRole('radio', { name: /Individual/ }).check()
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page).toHaveURL(`${origin}/app`)
  await page.reload()
  await expect(page.locator('.vx-workspace-tenant')).toContainText('Individual workspace')
})

